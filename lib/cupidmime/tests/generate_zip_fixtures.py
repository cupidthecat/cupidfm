"""Regenerate synthetic ZIP fixtures with Python's independent ZIP writer.

Optional maintenance tool; Python is not needed to build or run the C tests.
The EPUB samples identify a container marker, not a complete publication.
"""
import io
from pathlib import Path
import struct
import warnings
import zipfile


class Pipe(io.BytesIO):
    def seekable(self):
        return False

    def seek(self, *args):
        raise io.UnsupportedOperation("pipe")


def archive(compression=zipfile.ZIP_STORED, streaming=False, duplicate=False):
    out = Pipe() if streaming else io.BytesIO()
    with zipfile.ZipFile(out, "w") as z:
        second = ("mimetype", b"application/not-epub") if duplicate else ("META-INF/container.xml", b"<container/>")
        for name, content in [("mimetype", b"application/epub+zip"), second]:
            info = zipfile.ZipInfo(name, date_time=(2020, 1, 1, 0, 0, 0))
            info.compress_type = compression if name == "mimetype" else zipfile.ZIP_STORED
            info.create_system = 3
            info.external_attr = 0o600 << 16
            with warnings.catch_warnings():
                warnings.simplefilter("ignore", UserWarning)  # Deliberate duplicate-name fixture.
                z.writestr(info, content)
    return out.getvalue()


lines = ["/* Generated by tests/generate_zip_fixtures.py; synthetic test data. */",
         "#ifndef CM_ZIP_FIXTURES_H", "#define CM_ZIP_FIXTURES_H"]
for name, data in [("epub", archive()), ("compressed", archive(zipfile.ZIP_DEFLATED)),
                   ("streaming", archive(streaming=True)), ("duplicate", archive(duplicate=True))]:
    end = data.rindex(b"PK\x05\x06")
    cd = struct.unpack_from("<I", data, end+16)[0]
    second = cd+46+struct.unpack_from("<H", data, cd+28)[0]
    local = struct.unpack_from("<I", data, second+42)[0]
    for suffix, value in [("END", end), ("CD", cd), ("SECOND_CD", second), ("SECOND_LOCAL", local)]:
        lines.append(f"#define {name.upper()}_{suffix} {value}u")
    lines.append(f"static const unsigned char {name}_zip[] = {{")
    for i in range(0, len(data), 16):
        lines.append("    " + ",".join(f"0x{b:02x}" for b in data[i:i+16]) + ",")
    lines.append("};")
lines.append("#endif")
Path(__file__).with_name("zip_fixtures.h").write_text("\n".join(lines)+"\n")
